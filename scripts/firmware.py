#!/usr/bin/env python3
"""Firmware: an ESPHome config generated from each panel.

Reads a panel through panels.py and the catalog, and writes
build/panels/<name>/<name>.yaml: the hand written packages in
firmware/packages/ included with substitutions, nothing else. The base
package (ESP32-H2, deep sleep) comes first, then the radio package
(zigbee.yaml, ADR-0003), then one package per component, chosen by its
catalog family (FAMILY_PACKAGES). Each component's entity is named after
its id in the panel JSON, on the pins panels.assign_pins gives it: var
pin for a family's only pin, pin_<role> for the others (an encoder's
pin_a, pin_b, pin_push).

A display (display.yaml) is no entity: it shows the knob
panels.display_source picks, and every event of the panel's other
controls lights it, through one event package (FAMILY_EVENTS) per
entity and display. A pilot lamp (lamp.yaml) is no entity either: the
control it follows (panels.lamp_source) lights it, through one event
package (FOLLOW_EVENTS) per lamp. A panel with a display or a lamp
includes lit.yaml once, which keeps it awake while one is lit.

Firmware is a consumer of the panel and the catalog only: nothing on the
CAD side reads anything written here.

ESPHome comes from the nixpkgs pin in render_scad.py, the same way
OpenSCAD does. No-nix escape hatch: ESPHOME=/path/to/esphome.

Usage:
    scripts/firmware.py [name ...]         # write the configs (default: every panel)
    scripts/firmware.py --check [name ...] # and validate each with esphome config
"""

import json
import os
import re
import subprocess
import sys
from pathlib import Path

import panels
from render_scad import nix_path

ROOT = Path(__file__).resolve().parent.parent
PACKAGES = ROOT / "firmware" / "packages"
BUILD = ROOT / "build"
BASE = "h2_base.yaml"
RADIO = "zigbee.yaml"
LIT = "lit.yaml"
# catalog family -> its package in firmware/packages/
FAMILY_PACKAGES = {
    "toggle": "toggle.yaml",
    "encoder": "encoder.yaml",
    "rotary": "rotary.yaml",
    "pushbutton": "pushbutton.yaml",
    "display": "display.yaml",
    "lamp": "lamp.yaml",
}
# catalog family -> (event package, entity id suffix) for each entity of
# the family whose events light a display. A rotary switch lights none:
# its first reading at every wake looks like a turn.
FAMILY_EVENTS = {
    "toggle": [("display_on_binary.yaml", "")],
    "pushbutton": [("display_on_binary.yaml", "")],
    "encoder": [("display_on_turn.yaml", ""), ("display_on_binary.yaml", "_push")],
}
# catalog family -> (event package, entity id suffix) of the entity a
# lamp following a component of the family follows: a toggle's position,
# a press of a pushbutton or of an encoder's push.
FOLLOW_EVENTS = {
    "toggle": ("lamp_on_toggle.yaml", ""),
    "pushbutton": ("lamp_on_press.yaml", ""),
    "encoder": ("lamp_on_press.yaml", "_push"),
}
# catalog family -> catalog fields its package takes as vars
FAMILY_VARS = {"rotary": ["positions"]}
MODEL_MAX = 31  # Zigbee basic cluster model string


def esphome_binary() -> str:
    """The ESPHome to use: $ESPHOME if set, else the pinned nix one."""
    return os.environ.get("ESPHOME") or nix_path("esphome") + "/bin/esphome"


def node_name(name: str) -> str:
    """ESPHome node name: lowercase letters, digits and hyphens."""
    return "vippa-" + re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def entity_id(family: str, cid: str) -> str:
    """A C++ identifier for a component id, prefixed with its family so
    that no id can hit one ESPHome reserves."""
    return f"{family}_" + re.sub(r"\W", "_", str(cid), flags=re.ASCII)


def config(name, panel, catalog, out: Path) -> Path:
    """Write the ESPHome config for one valid panel to out (a .yaml path)."""
    pins, errors = panels.assign_pins(panel, catalog)
    if errors:
        raise ValueError("; ".join(errors))
    q = json.dumps  # a JSON string is a valid YAML scalar
    rel = lambda f: q(os.path.relpath(PACKAGES / f, out.parent))  # noqa: E731
    node = node_name(name)
    lines = [
        f"# GENERATED by scripts/firmware.py from panels/{name}.json and the catalog.",
        "# Do not edit: change the JSON and run scripts/regen_all.py.",
        "substitutions:",
        f"  name: {q(node)}",
        f"  model: {q(node[:MODEL_MAX])}",
        "",
        "packages:",
        f"  base: !include {rel(BASE)}",
        f"  radio: !include {rel(RADIO)}",
    ]
    lit = panels.DISPLAYS | panels.LAMPS
    if any(catalog[c["type"]]["family"] in lit for c in panel["components"]):
        lines.append(f"  lit: !include {rel(LIT)}")
    for c in panel["components"]:
        entry = catalog[c["type"]]
        family = entry["family"]
        if family not in FAMILY_PACKAGES:
            raise ValueError(f"{c['id']}: no firmware package for family {family!r}")
        eid = entity_id(family, c["id"])
        lines += [
            f"  {eid}: !include",
            f"    file: {rel(FAMILY_PACKAGES[family])}",
            "    vars:",
            f"      id: {eid}",
        ]
        if family in panels.DISPLAYS:
            shown = next(k for k in panel["components"]
                         if k["id"] == panels.display_source(c, panel["components"], catalog))
            lines.append(f"      value: {entity_id(catalog[shown['type']]['family'], shown['id'])}")
        elif family not in panels.LAMPS:
            lines.append(f"      name: {q(str(c['id']))}")
        lines += [f"      {'pin' if role == 'pin' else 'pin_' + role}: GPIO{pin}"
                  for role, pin in pins[c["id"]].items()]
        lines += [f"      {field}: {q(entry[field])}" for field in FAMILY_VARS.get(family, [])]
    displays = [entity_id("display", c["id"]) for c in panel["components"]
                if catalog[c["type"]]["family"] in panels.DISPLAYS]
    for c in panel["components"]:
        family = catalog[c["type"]]["family"]
        for package, suffix in FAMILY_EVENTS.get(family, []):
            source = entity_id(family, c["id"]) + suffix
            for did in displays:
                lines += [
                    f"  {did}_on_{source}: !include",
                    f"    file: {rel(package)}",
                    "    vars:",
                    f"      source: {source}",
                    f"      display: {did}",
                ]
    for c in panel["components"]:
        if catalog[c["type"]]["family"] not in panels.LAMPS:
            continue
        followed = panels.lamp_source(c, panel["components"], catalog)
        family = catalog[followed["type"]]["family"]
        package, suffix = FOLLOW_EVENTS[family]
        lid = entity_id("lamp", c["id"])
        lines += [
            f"  {lid}_on: !include",
            f"    file: {rel(package)}",
            "    vars:",
            f"      source: {entity_id(family, followed['id']) + suffix}",
            f"      lamp: {lid}",
        ]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    return out


def validate(yaml: Path, shown: Path) -> bool:
    """esphome config on one generated file; print [ok] or [FAIL]."""
    env = dict(os.environ)
    if "ESPHOME" not in env:
        env["LD_LIBRARY_PATH"] = ""  # the sandbox's /lib crashes nix binaries
    proc = subprocess.run([esphome_binary(), "config", str(yaml)], cwd=yaml.parent,
                          env=env, capture_output=True, text=True)
    out = proc.stdout + proc.stderr
    warnings = sorted({l.strip() for l in out.splitlines() if l.startswith(("WARNING", "ERROR"))})
    ok = proc.returncode == 0 and not warnings
    print(f"[{'ok' if ok else 'FAIL'}] {shown.relative_to(ROOT)} (esphome config)", flush=True)
    for w in warnings:
        print(f"        {w}")
    if proc.returncode != 0 and not warnings:
        print("        " + "\n        ".join(out.strip().splitlines()[-15:]))
    return ok


def main(argv):
    check = "--check" in argv
    names = [a for a in argv[1:] if not a.startswith("--")] or panels.panel_names()
    catalog, errors = panels.load_catalog()
    if errors:
        print("[FAIL] catalog is invalid, run scripts/panels.py")
        return 1
    ok = True
    for name in names:
        panel = panels.load_panel(name)
        if panels.validate(panel, catalog):
            print(f"[FAIL] panels/{name}.json is invalid, run scripts/panels.py {name}")
            ok = False
            continue
        out = config(name, panel, catalog, BUILD / "panels" / name / f"{name}.yaml")
        if check:
            ok &= validate(out, out)
        else:
            print(f"[ok] {out.relative_to(ROOT)}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
